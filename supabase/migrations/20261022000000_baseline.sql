CREATE OR REPLACE FUNCTION public.finish_and_maybe_restart_session(end_reason_input text DEFAULT NULL::text, auto_restart boolean DEFAULT true)
 RETURNS TABLE(finished_session_id bigint, restarted_session_id bigint)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
 v_user_id uuid;
 v_finished_id bigint;
 v_restarted_id bigint;
 v_now timestamptz := now();
begin
 v_user_id := auth.uid();

 if v_user_id is null then
 raise exception 'unauthorized';
 end if;

 -- いま動いている継続を終了
 update public.streak_sessions
 set ended_at = v_now,
 end_reason = nullif(trim(coalesce(end_reason_input, '')), '')
 where id = (
 select s.id
 from public.streak_sessions s
 where s.user_id = v_user_id
 and s.ended_at is null
 order by s.started_at desc
 limit 1
 )
 returning id into v_finished_id;

 if v_finished_id is null then
 raise exception 'no active session';
 end if;

 v_restarted_id := null;

 -- 次の継続を自動開始
 if auto_restart then
 insert into public.streak_sessions (user_id, started_at, ended_at, end_reason)
 values (v_user_id, v_now, null, null)
 returning id into v_restarted_id;
 end if;

 finished_session_id := v_finished_id;
 restarted_session_id := v_restarted_id;

 return next;
end;
$function$;


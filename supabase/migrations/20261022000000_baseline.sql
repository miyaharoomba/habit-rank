CREATE OR REPLACE FUNCTION public.get_leaderboard(limit_count integer DEFAULT 50)
 RETURNS TABLE(user_id uuid, display_name text, best_seconds bigint)
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
 with best as (
 select
 user_id,
 max(extract(epoch from (ended_at - started_at)))::bigint as best_seconds
 from public.streak_sessions
 where ended_at is not null
 group by user_id
 )
 select
 p.id as user_id,
 coalesce(p.display_name, 'User') as display_name,
 coalesce(b.best_seconds, 0) as best_seconds
 from public.profiles p
 left join best b on b.user_id = p.id
 order by best_seconds desc, p.created_at asc
 limit greatest(limit_count, 1);
$function$;


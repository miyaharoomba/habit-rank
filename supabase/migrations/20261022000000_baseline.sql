CREATE OR REPLACE FUNCTION public.enqueue_push_outbox()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
 v_title text;
 v_body text;
 v_url text;
begin
 -- typeごとの遷移先（既存仕様を踏襲）
 if new.type = 'dm' and new.thread_id is not null then
 v_title := coalesce(nullif(new.message_preview, ''), 'DMが届きました');
 v_body := coalesce(nullif(new.message_preview, ''), 'DMを確認してください');
 v_url := '/dm/' || new.thread_id::text;

 elsif new.type = 'streak_end' and new.session_id is not null then
 v_title := '継続リザルト';
 v_body := coalesce(nullif(new.message_preview, ''), '継続が終了しました');
 v_url := '/results/' || new.session_id::text;

 else
 v_title := '通知';
 v_body := coalesce(nullif(new.message_preview, ''), '新しい通知があります');
 v_url := '/app';
 end if;

 -- ✅ 全体通知（recipient_id is null）のときは fan-out
 if new.recipient_id is null then
 insert into public.push_outbox(notification_id, recipient_id, payload)
 select
 new.id,
 s.user_id,
 jsonb_build_object('title', v_title, 'body', v_body, 'url', v_url)
 from (
 select distinct user_id
 from public.push_subscriptions
 where disabled = false
 ) s;

 else
 -- 個人通知は1件だけ
 insert into public.push_outbox(notification_id, recipient_id, payload)
 values (
 new.id,
 new.recipient_id,
 jsonb_build_object('title', v_title, 'body', v_body, 'url', v_url)
 );
 end if;

 return new;
end;
$function$;


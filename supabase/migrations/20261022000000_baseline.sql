CREATE OR REPLACE FUNCTION public.profile_level_from_xp(p_xp numeric)
 RETURNS integer
 LANGUAGE sql
 IMMUTABLE
AS $function$
 select greatest(
 1,
 floor(
 (1 + sqrt(1 + (8 * greatest(coalesce(p_xp, 0), 0) / 100.0))) / 2
 )::integer
 );
$function$;

CREATE OR REPLACE FUNCTION public.streak_session_scaled_xp(p_started_at timestamp with time zone, p_ended_at timestamp with time zone)
 RETURNS numeric
 LANGUAGE sql
 IMMUTABLE
AS $function$
 with duration as (
 select greatest(
 0,
 extract(epoch from (p_ended_at - p_started_at)) / 60.0
 ) as minutes
 )
 select case
 when p_started_at is null or p_ended_at is null then 0::numeric
 when minutes <= 0 then 0::numeric
 else round(
 (
 minutes
 * least(
 2.2,
 0.1 + (1.1 * ln(greatest(minutes, 1)) / ln(1440))
 )
 )::numeric,
 1
 )
 end
 from duration;
$function$;

CREATE OR REPLACE FUNCTION public.refresh_profile_level(p_user_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
 v_xp numeric(12, 1);
begin
 if p_user_id is null then
 return;
 end if;

 select (
 coalesce((
 select sum(public.streak_session_scaled_xp(s.started_at, s.ended_at))
 from public.streak_sessions s
 where s.user_id = p_user_id and s.ended_at is not null
 ), 0)
 +
 coalesce((
 select sum(r.reward_xp)
 from public.minigame_runs r
 where r.user_id = p_user_id and r.status = 'finished'
 ), 0)
 )::numeric(12, 1)
 into v_xp;

 update public.profiles
 set xp_total = v_xp,
 level = public.profile_level_from_xp(v_xp)
 where id = p_user_id;
end;
$function$;


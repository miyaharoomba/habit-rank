CREATE OR REPLACE FUNCTION public.create_or_get_dm(other_user uuid)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
 me uuid;
 low uuid;
 high uuid;
 tid uuid;
begin
 me := auth.uid();
 if me is null then
 raise exception 'Not authenticated';
 end if;

 if other_user is null then
 raise exception 'other_user is required';
 end if;

 if other_user = me then
 raise exception 'Cannot DM yourself';
 end if;

 low := least(me, other_user);
 high := greatest(me, other_user);

 select id into tid
 from public.dm_threads
 where user_low = low and user_high = high;

 if tid is not null then
 return tid;
 end if;

 insert into public.dm_threads (user_low, user_high)
 values (low, high)
 returning id into tid;

 return tid;
end;
$function$;


CREATE OR REPLACE FUNCTION public.get_my_dm_threads(limit_count integer DEFAULT 50)
 RETURNS TABLE(thread_id uuid, other_user_id uuid, other_display_name text, last_message text, last_message_at timestamp with time zone, unread_count integer)
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
 with my_threads as (
 select
 t.id,
 case
 when t.user_low = auth.uid() then t.user_high
 else t.user_low
 end as other_user_id
 from public.dm_threads t
 where t.user_low = auth.uid()
 or t.user_high = auth.uid()
 ),
 last_messages as (
 select distinct on (m.thread_id)
 m.thread_id,
 case
 when m.unsent_at is not null then 'Unsent message'
 when nullif(trim(m.body), '') is not null then m.body
 when m.message_type = 'image' then 'Image'
 when m.message_type = 'video' then 'Video'

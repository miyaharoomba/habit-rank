CREATE OR REPLACE FUNCTION public.streak_session_xp(p_started_at timestamp with time zone, p_ended_at timestamp with time zone)
 RETURNS integer
 LANGUAGE sql
 IMMUTABLE
AS $function$
 select case
 when p_started_at is null or p_ended_at is null then 0
 else greatest(
 0,
 floor(extract(epoch from (p_ended_at - p_started_at)) / 60)::integer
 )
 end;
$function$;

